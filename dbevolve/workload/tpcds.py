"""TPC-DS, used as a transfer test: 99 fixed queries that the evolution loop never optimised for.

The query texts are the ones shipped with DuckDB's tpcds extension (spec default substitutions),
read from the engine clone. There are no parameter generators, so every template has exactly one
binding. Data is generated by a separate build that links the tpcds extension (see
`bin/dbe transfer`); every evaluated binary then loads the same Parquet files.
"""
from __future__ import annotations

import re
from pathlib import Path

from ..config import ROOT

QUERY_DIR = ROOT / "work" / "duckdb" / "extension" / "tpcds" / "dsdgen" / "queries"

TEMPLATES = [f"q{n:02d}" for n in range(1, 100)]

TABLES = ["call_center", "catalog_page", "catalog_returns", "catalog_sales", "customer", "customer_address",
          "customer_demographics", "date_dim", "household_demographics", "income_band", "inventory", "item",
          "promotion", "reason", "ship_mode", "store", "store_returns", "store_sales", "time_dim", "warehouse",
          "web_page", "web_returns", "web_sales", "web_site"]


def _query(template: str) -> str:
    text = (QUERY_DIR / f"{int(template[1:]):02d}.sql").read_text()
    lines = [re.sub(r"--.*$", "", line).strip() for line in text.splitlines()]
    return " ".join(x for x in lines if x).rstrip(";").strip()


def instantiate(template: str, rng, scale_factor: float) -> tuple[str, dict]:
    return _query(template), {"fixed": "spec defaults"}


def datagen_sql(scale_factor: float) -> str:
    return f"CALL dsdgen(sf={scale_factor:g})"


def audit_patterns() -> list[str]:
    return []
